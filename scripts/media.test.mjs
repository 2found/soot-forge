import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, stat } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';

const packs = ['office', 'ocr', 'tts', 'google-workspace', 'video-editor', 'image-gen'];
const root = new URL('../', import.meta.url);

test('media packs are standalone, opt-in and use operation-scoped host bindings', async () => {
  for (const id of packs) {
    const pack = new URL(`packs/${id}/`, root);
    const manifest = JSON.parse(await readFile(new URL('pack.json', pack), 'utf8'));
    assert.equal(manifest.id, id);
    for (const selector of manifest.use) {
      assert.ok(!(manifest.capabilities[selector].tools ?? []).some(t => t.run.mode !== 'read'), id);
    }
    for (const capability of Object.values(manifest.capabilities)) {
      for (const skill of capability.skills) {
        assert.ok((await readFile(new URL(skill.file, pack), 'utf8')).length > 250, `${id}/${skill.name}`);
      }
      for (const tool of capability.tools ?? []) {
        assert.equal(tool.run.program, 'tools/run');
        assert.deepEqual(tool.run.args, [tool.name]);
        assert.equal(tool.run.stdin, 'context');
        assert.equal(tool.parameters.additionalProperties, false);
        assert.ok(tool.run.secret_env.FILE_ROOT);
        assert.ok(!tool.run.env);
        assert.equal(tool.run.resource, 'file_workspace');
      }
    }
    assert.ok((await stat(new URL('tools/run', pack))).mode & 0o111);
    assert.ok((await readFile(new URL('requirements.lock', pack), 'utf8')).startsWith('# This file was autogenerated by uv'));
  }
});

test('copied wire/path/network support matches its reviewed source', () => {
  execFileSync('python3', [new URL('scripts/sync-media-support.py', root).pathname, '--check']);
});

test('Google Workspace covers three services with no automatic grants', async () => {
  const manifest = JSON.parse(await readFile(new URL('packs/google-workspace/pack.json', root), 'utf8'));
  const catalog = JSON.parse(await readFile(new URL('catalog.json', root), 'utf8'));
  assert.deepEqual(manifest.use, []);
  assert.ok(catalog.packs.some(p => p.id === 'google-workspace' && p.source.path === 'packs/google-workspace'));
  assert.ok(!catalog.packs.some(p => p.id === 'google-doc'));
  const tools = Object.values(manifest.capabilities).flatMap(cap => cap.tools ?? []);
  assert.equal(tools.length, 17);
  for (const prefix of ['docs_', 'sheets_', 'drive_']) assert.ok(tools.some(t => t.name.startsWith(prefix)));
  for (const tool of tools) {
    assert.ok(tool.run.secret_env.GOOGLE_WORKSPACE_BINDING);
    assert.ok(!tool.run.secret_env.GOOGLE_DOC_BINDING);
  }
  const host = JSON.parse(await readFile(new URL('examples/media-workspace/deployment.example.json', root), 'utf8'));
  const operations = host.credentials['google-workspace'].GOOGLE_WORKSPACE_BINDING.operations;
  assert.deepEqual(new Set(operations), new Set(tools.map(t => `google-workspace_${t.name}`)));
});

test('optional HyperFrames host dependency is pinned and locked', async () => {
  const folder = new URL('packs/video-editor/operator/hyperframes/', root);
  const manifest = JSON.parse(await readFile(new URL('package.json', folder), 'utf8'));
  const lock = JSON.parse(await readFile(new URL('package-lock.json', folder), 'utf8'));
  assert.equal(manifest.dependencies.hyperframes, '0.8.143');
  assert.equal(lock.packages['node_modules/hyperframes'].version, '0.8.143');
  assert.ok(lock.packages['node_modules/hyperframes'].integrity.startsWith('sha512-'));
});
